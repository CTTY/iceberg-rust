// Creates a runtime.
//
// `workers` is the number of tokio worker threads and `blocking` the maximum
// number of threads for blocking work; both must be at least 1.
// `alloc_error` must not be null; it is used for every error reported
// through this runtime, including the error of this call, and a null pointer
// is undefined behaviour. `log_cb` may be null to disable log
// forwarding; otherwise it is invoked with `log_ctx` as its first argument,
// possibly concurrently from several threads, for as long as the runtime is
// alive, so `log_ctx` must stay valid until `iceberg_runtime_free` returns.
//
// On success the engine owns the returned handle and must release it with
// `iceberg_runtime_free`.
struct IcebergResultRuntime iceberg_runtime_new(uint32_t workers,
                                                uint32_t blocking,
                                                IcebergAllocateErrorFn alloc_error,
                                                IcebergLogCallbackFn log_cb,
                                                void *log_ctx);

// Releases the engine's reference to a runtime.
//
// Log forwarding stops before anything else happens, since the engine may
// free `log_ctx` as soon as this returns. When this was the last reference,
// worker threads are asked to stop and given a short grace period. A null
// handle is ignored. Must not be called from a thread inside the runtime.
void iceberg_runtime_free(IcebergSharedRuntime runtime);

// Creates a scan builder for `table` with the defaults: current snapshot,
// every column, case-sensitive names, no predicate.
//
// The engine owns the returned handle until it passes it to
// `iceberg_scan_builder_build` or `iceberg_scan_builder_free`.
struct IcebergResultScanBuilder iceberg_scan_builder_new(IcebergSharedTable table);

// Releases a scan builder that was not built. A null handle is ignored.
void iceberg_scan_builder_free(IcebergExclusiveScanBuilder builder);

// Scans snapshot `snapshot_id` instead of the current one. The snapshot's
// own schema is used for binding and projection; an unknown id is reported
// by `iceberg_scan_builder_build` as `IcebergErrorCodeInvalidArgument`.
struct IcebergResultUnit iceberg_scan_builder_snapshot_id(IcebergExclusiveScanBuilder builder,
                                                          int64_t snapshot_id);

// Projects only the `n` top-level columns with these field ids, in this
// order; `n == 0` projects no columns. Replaces an earlier selection. Ids
// are validated at build time: a nested id is
// `IcebergErrorCodeFeatureUnsupported`, an unknown id
// `IcebergErrorCodeInvalidArgument`.
struct IcebergResultUnit iceberg_scan_builder_select_field_ids(IcebergExclusiveScanBuilder builder,
                                                               const int32_t *field_ids,
                                                               size_t n);

// Whether column names in the predicate are matched case-sensitively
// (default true).
struct IcebergResultUnit iceberg_scan_builder_case_sensitive(IcebergExclusiveScanBuilder builder,
                                                             bool case_sensitive);

// Builds the predicate by calling `visitor(ctx, state)` immediately, on the
// calling thread; see the `predicate` module for the arena protocol.
//
// The visitor returns the root node id, or `ICEBERG_PRED_NONE` to clear the
// predicate. A failed state, or a root that is not a predicate node, is
// `IcebergErrorCodeInvalidArgument` and leaves the builder's previous
// predicate in place.
struct IcebergResultUnit iceberg_scan_builder_set_predicate(IcebergExclusiveScanBuilder builder,
                                                            void *ctx,
                                                            IcebergPredicateVisitorFn visitor);

// Consumes the builder, plans the scan and returns it.
//
// The builder is freed on every path, including a null runtime. `runtime`
// must be the runtime the table was loaded with. Planning reads the
// snapshot's manifest list and manifests through the table's file system
// and collects every file task before returning.
//
// Errors: a predicate that cannot be bound to the snapshot schema is
// `IcebergErrorCodePredicateBindFailed` (retry without a predicate); see
// `iceberg_scan_builder_snapshot_id` and
// `iceberg_scan_builder_select_field_ids` for theirs.
struct IcebergResultScan iceberg_scan_builder_build(IcebergSharedRuntime runtime,
                                                    IcebergExclusiveScanBuilder builder);

// Releases the engine's reference to a scan. Task handles already handed
// out stay valid. A null handle is ignored.
void iceberg_scan_free(IcebergSharedScan scan);

// Number of file tasks in the scan; 0 for a null handle.
size_t iceberg_scan_file_task_count(IcebergSharedScan scan);

// The snapshot the scan was planned from; absent when the table had no
// snapshot (the scan is then empty) or the handle is null.
struct IcebergOptionalI64 iceberg_scan_snapshot_id(IcebergSharedScan scan);

// Union of the equality field ids of every equality delete file in the
// scan, sorted and without duplicates.
//
// Copies at most `cap` ids into `out` and returns the total count, so call
// once with `cap == 0` to size the buffer and once more to fill it. A null
// `out` is treated as `cap == 0` whatever `cap` says. Returns 0 for a null
// handle.
size_t iceberg_scan_equality_field_ids(IcebergSharedScan scan, int32_t *out, size_t cap);

// Delivers task `index` (0-based, in data file path order) to `cb` as an
// [`IcebergFileTaskInfo`] plus a task handle the engine owns.
//
// `index >= iceberg_scan_file_task_count` is
// `IcebergErrorCodeInvalidArgument`. A task that does not cover its whole
// file is `IcebergErrorCodeFeatureUnsupported`; one without a record count
// or partition spec is `IcebergErrorCodeDataInvalid`; `cb` is not called in
// those cases.
struct IcebergResultUnit iceberg_scan_file_task(IcebergSharedScan scan,
                                                size_t index,
                                                void *ctx,
                                                IcebergFileTaskCallbackFn cb);

// Releases the engine's reference to a file task. A null handle is ignored.
void iceberg_file_task_free(IcebergSharedFileTask task);

// The field ids the task projects, in selection order (every top-level
// column when nothing was selected).
//
// Same two-call pattern as `iceberg_scan_equality_field_ids`; returns 0 for
// a null handle.
size_t iceberg_file_task_project_field_ids(IcebergSharedFileTask task, int32_t *out, size_t cap);

// Calls `cb(ctx, source_field_id, value)` for every identity-transformed
// partition field of the task's file, in ascending source field id order.
//
// Only identity transforms contribute; bucket, truncate and time transforms
// cannot reconstruct the column and are skipped. A null partition value is
// skipped as well, so the engine reads the column (or NULL) from the data
// file. Unpartitioned files produce no calls.
struct IcebergResultUnit iceberg_file_task_visit_partition_constants(IcebergSharedFileTask task,
                                                                     void *ctx,
                                                                     IcebergPartitionConstantCallbackFn cb);

// Calls `cb` once per delete file that applies to the task's data file, in
// manifest order; see [`IcebergDeleteFileCallbackFn`] for the arguments.
struct IcebergResultUnit iceberg_file_task_visit_deletes(IcebergSharedFileTask task,
                                                         void *ctx,
                                                         IcebergDeleteFileCallbackFn cb);

// Delivers one of the table's schemas through `visitor` and returns the id
// of the root field list.
//
// `schema_id` absent selects the current schema; an unknown id is
// `IcebergErrorCodeInvalidArgument`, as is a null `visitor`. Geometry and
// geography columns are `IcebergErrorCodeFeatureUnsupported`. Callbacks
// already made before an error are not undone; the engine should discard
// the lists it created.
struct IcebergResultUsize iceberg_table_visit_schema(IcebergSharedTable table,
                                                     struct IcebergOptionalI32 schema_id,
                                                     const struct IcebergSchemaVisitor *visitor);

// Loads a table from a metadata JSON file.
//
// `fs` is the engine file system every read goes through; this call takes
// ownership of `fs.ctx` and `release` runs exactly once, either from
// `iceberg_table_free` or, when loading fails (including a null runtime),
// before this function returns. `metadata_location` is the path of the
// `*.metadata.json` file, as the engine's file system understands it; gzip
// compressed metadata is detected from the content.
//
// `relocate_from` and `relocate_to` are either both empty (no relocation)
// or both set, in which case every path recorded in the table that starts
// with `relocate_from` is rewritten to start with `relocate_to` before it
// reaches `fs`. One empty and one set is `IcebergErrorCodeInvalidArgument`.
//
// On success the engine owns the returned handle and must release it with
// `iceberg_table_free`.
struct IcebergResultTable iceberg_table_load(IcebergSharedRuntime runtime,
                                             struct IcebergFileSystemVTable fs,
                                             struct IcebergStringSlice metadata_location,
                                             struct IcebergStringSlice relocate_from,
                                             struct IcebergStringSlice relocate_to);

