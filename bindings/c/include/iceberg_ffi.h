// `bucket[4]`, `day`, ...). The string slices are valid only during the
// callback. Must not unwind.
typedef void (*IcebergPartitionFieldCallbackFn)(void*,
                                                int32_t,
                                                int32_t,
                                                struct IcebergStringSlice,
                                                struct IcebergStringSlice);

